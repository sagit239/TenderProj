// One-off: writes the Israeli non-workday holidays (2026–2031) as a migration file.
// Run with: node scripts/generate-holidays.mjs <output.sql>
import { writeFileSync } from "node:fs";
import { HebrewCalendar, flags } from "@hebcal/core";

const [output] = process.argv.slice(2);
if (!output) {
  console.error("Usage: node scripts/generate-holidays.mjs <output.sql>");
  process.exit(1);
}

// Days on which offices are closed: yom tov days in Israel, Independence Day,
// and holiday eves (user decision, ADR-6). Chol HaMoed stays a workday.
const NAMES = {
  "Rosh Hashana": "ראש השנה",
  "Rosh Hashana II": "ראש השנה (יום ב')",
  "Yom Kippur": "יום כיפור",
  "Sukkot I": "סוכות",
  "Shmini Atzeret": "שמיני עצרת / שמחת תורה",
  "Pesach I": "פסח",
  "Pesach VII": "שביעי של פסח",
  Shavuot: "שבועות",
  "Yom HaAtzma'ut": "יום העצמאות",
  "Erev Rosh Hashana": "ערב ראש השנה",
  "Erev Yom Kippur": "ערב יום כיפור",
  "Erev Sukkot": "ערב סוכות",
  "Sukkot VII (Hoshana Raba)": "הושענא רבה (ערב שמיני עצרת)",
  "Erev Pesach": "ערב פסח",
  "Pesach VI (CH''M)": "ערב שביעי של פסח",
  "Erev Shavuot": "ערב שבועות",
};

const rows = [];
for (let year = 2026; year <= 2031; year++) {
  const events = HebrewCalendar.calendar({
    start: new Date(year, 0, 1),
    end: new Date(year, 11, 31),
    il: true,
    mask: flags.CHAG | flags.MODERN_HOLIDAY | flags.EREV | flags.CHOL_HAMOED,
  });
  for (const ev of events) {
    const desc = ev.getDesc().replace(/ \d{4}$/, "");
    const name = NAMES[desc];
    if (!name) continue;
    const d = ev.getDate().greg();
    const iso = `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-${String(d.getDate()).padStart(2, "0")}`;
    rows.push([iso, name]);
  }
}
rows.sort((a, b) => a[0].localeCompare(b[0]));

const values = rows.map(([date, name]) => `  ('${date}', '${name.replace(/'/g, "''")}')`).join(",\n");
writeFileSync(
  output,
  `-- Milestone 3: Israeli holidays that are not workdays (generated by scripts/generate-holidays.mjs)\n` +
    `insert into public.holidays (date, name) values\n${values}\non conflict (date) do nothing;\n\n` +
    `insert into public.app_migrations (name) values ('20261102160100_m3_holidays')\n` +
    `  on conflict (name) do nothing;\n`,
);
console.log(rows.map(([d, n]) => `${d}  ${n}`).join("\n"));
console.log(`\n${rows.length} days written to ${output}`);
