-- Milestone 1: roles become a table, so the user can add new roles from the UI

create table public.roles (
  key text primary key default gen_random_uuid()::text,
  label text not null unique check (length(trim(label)) > 0),
  sort_order integer generated by default as identity,
  created_at timestamptz not null default now()
);
alter table public.roles enable row level security;
create policy "authenticated full access" on public.roles
  for all to authenticated using (true) with check (true);

-- The six original roles, in their original order
