  ('service_manager', 'מנהל שירות');

-- Replace the fixed list check with a reference to the roles table
alter table public.team_members drop constraint if exists team_members_role_check;
alter table public.team_members
  add constraint team_members_role_fkey foreign key (role) references public.roles (key)
  on update cascade;

